#!/usr/bin/env python3
"""Deploy and run our cross-built app on the rooted Harmony Elite remote, over USB Ethernet SSH.

Files go only under /data/app (persistent), /etc/init.d/rcS.local (the boot hook; staged next to
it, checked with `sh -n` ON the device, then mv'd) and /var/volatile (tmpfs). Never touches any mtd/ubi node, rffw,
mspfw, the watchdog, the charger or power-state sysfs files, and never uses dd.

The boot hook is one guarded line in rcS.local that backgrounds /data/app/start.sh after dropbear
(so it can never block SSH). start.sh counts boots; after 3 boots that were never marked good it
writes /data/app/DISABLE and stops launching the app. Touch /data/app/DISABLE to kill it by hand.
Recovery of last resort is Menu+Off (factory reset).

Subcommands are marked [read-only] or [WRITE]; every WRITE one needs --yes.
"""

import argparse
import hashlib
import posixpath
import re
import shlex
import sys
import time
from collections.abc import Callable
from pathlib import Path

from deploy_hub import DeployError, HubSsh, Runner, parse_ps
from device_backup import DEFAULT_RUN_TIMEOUT, DEFAULT_SSH_TIMEOUT, parse_hash

APP_DIR = "/data/app"
RCS_LOCAL = "/etc/init.d/rcS.local"
RCS_TMP = RCS_LOCAL + ".new"
RCS_BACKUP = f"{APP_DIR}/rcS.local.orig"
START_SH = f"{APP_DIR}/start.sh"
BOOTCOUNT = f"{APP_DIR}/bootcount"
DISABLE = f"{APP_DIR}/DISABLE"
DEFAULT_APP = "harmony_remote"
MAX_BOOTS = 3
# Bench-proven RF settings (bench session 1): without them the app defaults to slot 0 /
# powermode 0x00 and would boot "healthy" with the radio dead.
DEFAULT_SLOT = 1
DEFAULT_POWERMODE = "0x30"
SELFTEST_SRC = Path(__file__).resolve().parent / "boot" / "remote_selftest.sh"
SELFTEST_DIR = "/var/volatile/hah-selftest"  # tmpfs; the ONLY place selftest writes
HOOK_MARKER = "# ha-harmony-hook"
# The PMIC exposes its nodes on a sub-device, not the i2c client itself (verified on the
# Elite 2026-11-17; the bare 1-0048/powersource does not exist).
POWERSOURCE = "/sys/bus/i2c/devices/1-0048/tps6507x-juniper/powersource"
SOC = "/sys/bus/i2c/devices/1-0070/soc"
VOLATILE = "/var/volatile"


def parse_slot(v: str) -> int:
    if not re.fullmatch(r"[0-9]{1,2}", v) or not 1 <= int(v) <= 15:
        raise argparse.ArgumentTypeError(f"--slot must be 1..15, got {v!r}")
    return int(v)


def parse_powermode(v: str) -> str:
    if not re.fullmatch(r"0x[0-9a-fA-F]{2}", v):
        raise argparse.ArgumentTypeError(f"--powermode must look like 0x30, got {v!r}")
    return "0x" + v[2:].lower()


def under_write_root(path: str) -> bool:
    """True only for /data/app/*, the rcS.local pair, and /var/volatile/*."""
    if ".." in path.split("/"):
        return False
    n = posixpath.normpath(path)
    return n in (RCS_LOCAL, RCS_TMP) or any(n.startswith(r + "/") for r in (APP_DIR, VOLATILE))


def _need_write(path: str) -> str:
    if not under_write_root(path):
        raise DeployError(f"internal error: refusing to write outside the allowed paths: {path}")
    return path


def hook_line(app_dir: str = APP_DIR) -> str:
    q = shlex.quote
    return (
        f"[ -x {q(app_dir + '/start.sh')} ] && [ ! -e {q(app_dir + '/DISABLE')} ] && "
        f"{q(app_dir + '/start.sh')} &  {HOOK_MARKER}"
    )


START_TEMPLATE = """#!/bin/sh
# Generated by deploy_remote.py. Counts boots; disables itself after @MAX@ unhealthy ones.
# Backgrounded by rcS.local, so it can never block SSH. Only shell builtins plus sleep/kill;
# no arithmetic on file content; every redirect that can fail is guarded.
APP_DIR="${APP_DIR:-@APPDIR@}"
APP_BIN="${APP_BIN:-$APP_DIR/@APP@}"
APP_LOG="${APP_LOG:-@LOG@}"
LOG_MAX="${START_LOG_MAX_LINES:-@LOGMAX@}"
TICK="${START_TICK:-30}"
case "$LOG_MAX" in '' | *[!0-9]*) LOG_MAX=@LOGMAX@ ;; esac
# Whole seconds on the device (BusyBox 1.13 sleep); tests pass a fraction via START_TICK.
case "$TICK" in '' | *[!0-9.]*) TICK=30 ;; esac
COUNT_FILE="$APP_DIR/bootcount"
[ -e "$APP_DIR/DISABLE" ] && exit 0
n=''
[ -f "$COUNT_FILE" ] && read -r n < "$COUNT_FILE"
# Only the values this script itself writes count; anything else (empty, 08, garbage) is clean.
case "$n" in 0 | 1 | 2 | 3) ;; *) n=0 ;; esac
n=$((n + 1))
# No counter, no launch: a crash loop we cannot count must not run.
{ echo "$n" > "$COUNT_FILE"; } 2>/dev/null || exit 0
if [ "$n" -gt @MAX@ ]; then
    { true > "$APP_DIR/DISABLE"; } 2>/dev/null
    exit 0
fi
[ -x "$APP_BIN" ] || exit 0
{ true >> "$APP_LOG"; } 2>/dev/null || APP_LOG=/dev/null
# The app (or `deploy_remote.py mark-good`) writes 0 here once it is healthy.
export HARMONY_BOOTCOUNT_FILE="$COUNT_FILE"
# Every app line (and ours) is prefixed with the uptime, so the log can be read against a
# crash or a reboot. `$!` of a pipeline is the stamping loop: it ends when the app (and so the
# pipe) closes, which is exactly the liveness the watcher below needs.
stamp() {
    while l=''; IFS= read -r l || [ -n "$l" ]; do
        up=''
        read -r up _ 2>/dev/null < /proc/uptime
        printf '[up %ss] %s\n' "${up%%.*}" "$l"
    done
}
echo "start.sh: launching the app (boot $n of @MAX@)" | stamp >> "$APP_LOG" 2>/dev/null
"$APP_BIN" @ARGV@ 2>&1 < /dev/null | stamp >> "$APP_LOG" 2>/dev/null &
pid=$!
# Keep the tmpfs log bounded: truncate in place (the app writes O_APPEND) when over LOG_MAX lines.
while kill -0 "$pid" 2>/dev/null; do
    sleep "$TICK"
    lines=0
    while IFS= read -r _l; do
        lines=$((lines + 1))
        [ "$lines" -gt "$LOG_MAX" ] && break
    done < "$APP_LOG" 2>/dev/null
    [ "$lines" -gt "$LOG_MAX" ] && { true > "$APP_LOG"; } 2>/dev/null
done
exit 0
"""


def start_script(
    app: str = DEFAULT_APP,
    max_boots: int = MAX_BOOTS,
    slot: int = DEFAULT_SLOT,
    powermode: str = DEFAULT_POWERMODE,
) -> str:
    """start.sh: boot counter + crash-loop breaker. Paths are overridable for tests."""
    argv = f"--slot {parse_slot(str(slot))} --powermode {parse_powermode(powermode)}"
    out = START_TEMPLATE
    for k, v in (
        ("@MAX@", str(max_boots)),
        ("@APPDIR@", APP_DIR),
        ("@APP@", app),
        ("@LOG@", f"{VOLATILE}/ha-harmony-app.log"),
        ("@LOGMAX@", "5000"),
        ("@ARGV@", argv),
    ):
        out = out.replace(k, v)
    return out


def start_argv(slot: int = DEFAULT_SLOT, powermode: str = DEFAULT_POWERMODE) -> str:
    return f"--slot {slot} --powermode {powermode}"


def rcs_shape_problem(text: str, hooked: bool) -> str | None:
    """None if rcS.local has dropbear (before the hook, if any) and a trailing `exit 0`."""
    lines = text.split("\n")
    body = [i for i, ln in enumerate(lines) if ln.strip()]
    exit_i = body[-1] if body else -1
    if exit_i < 0 or lines[exit_i].strip() != "exit 0":
        return "does not end with `exit 0`"
    db = [i for i, ln in enumerate(lines) if "dropbear" in ln and not ln.lstrip().startswith("#")]
    if not db or db[0] > exit_i:
        return "has no dropbear start line before `exit 0`"
    marks = [i for i, ln in enumerate(lines) if HOOK_MARKER in ln]
    if hooked:
        if len(marks) != 1 or not db[0] < marks[0] < exit_i:
            return "hook line is not exactly once, after dropbear and before `exit 0`"
    elif marks:
        return "still contains the hook line"
    return None


def insert_hook(text: str) -> str:
    """Add the hook before the final `exit 0`; refuse any rcS.local of an unknown shape."""
    lines = text.split("\n")
    body = [i for i, ln in enumerate(lines) if ln.strip()]
    exit_i = body[-1] if body else -1
    has_exit = exit_i >= 0 and lines[exit_i].strip() == "exit 0"
    dropbear_i = [
        i for i, ln in enumerate(lines) if "dropbear" in ln and not ln.lstrip().startswith("#")
    ]
    if not has_exit or not dropbear_i or dropbear_i[0] > exit_i:
        raise DeployError(
            f"{RCS_LOCAL} has an unknown shape (need a dropbear line and a trailing `exit 0`); "
            f"NOT editing. Found:\n{text}"
        )
    lines.insert(exit_i, hook_line())
    return "\n".join(lines)


def _md5(data: bytes) -> str:
    return hashlib.md5(data, usedforsecurity=False).hexdigest()


def _dec(b: bytes) -> str:
    return b.decode("utf-8", "replace")


class RemoteDeployer:
    def __init__(
        self,
        runner: Runner,
        out: Callable[[str], None] = print,
        sleep: Callable[[float], None] = time.sleep,
        clock: Callable[[], float] = time.monotonic,
    ) -> None:
        self.r, self.out, self.sleep, self.clock = runner, out, sleep, clock

    # -- helpers ------------------------------------------------------------------------
    def connect(self) -> str:
        rc, out, err = self.r.run(["uname", "-a"])
        if rc != 0:
            raise DeployError(f"ssh/uname failed (rc={rc}): {_dec(err)[-200:]}")
        return _dec(out).strip()

    def read(self, path: str) -> bytes | None:
        rc, out, _ = self.r.run(["cat", path])
        return out if rc == 0 else None

    def exists(self, path: str) -> bool:
        return self.r.run(["test", "-e", path])[0] == 0

    def wait(self, pred: Callable[[], bool], timeout: float, interval: float = 2.0) -> bool:
        deadline = self.clock() + timeout
        while True:
            if pred():
                return True
            if self.clock() >= deadline:
                return False
            self.sleep(interval)

    def _stage(
        self, data: bytes, tmp: str, mode: str | None, dest: str, syntax: bool = False
    ) -> str:
        """Upload to a temp, verify md5, optionally `sh -n` it ON the device, chmod. Never mv."""
        _need_write(dest)
        _need_write(tmp)
        want = _md5(data)

        def drop(msg: str) -> DeployError:
            self.r.run(["rm", "-f", tmp])  # never leave an unverified file behind
            return DeployError(msg)

        rc, _, err = self.r.run_input(["sh", "-c", f"cat > {shlex.quote(tmp)}"], data)
        if rc != 0:
            raise drop(f"{dest}: upload failed (rc={rc}): {_dec(err)}")
        rc, out, _ = self.r.run(["md5sum", tmp])
        got = parse_hash(out, "md5") if rc == 0 else None
        if got != want:
            raise drop(
                f"{dest}: md5 MISMATCH (local {want}, device {got or 'unreadable'}); "
                "temp file removed, destination untouched"
            )
        if syntax:
            rc, _, err = self.r.run(["sh", "-n", tmp])
            if rc != 0:
                raise drop(
                    f"{dest}: `sh -n` on the device rejects the candidate: {_dec(err)[-200:]}; "
                    "temp file removed, destination untouched"
                )
        if mode:
            rc, _, err = self.r.run(["chmod", mode, tmp])
            if rc != 0:
                raise drop(f"{dest}: chmod failed: {_dec(err)}")
            if mode == "755" and self.r.run(["test", "-x", tmp])[0] != 0:
                raise drop(f"{dest}: candidate is not executable after chmod")
        return want

    def _put(
        self,
        data: bytes,
        dest: str,
        mode: str | None,
        tmp: str | None = None,
        syntax: bool = False,
    ) -> None:
        """Md5-verified write: stage a temp in the same directory, verify, mv, verify again."""
        tmp = tmp or dest + ".new"
        want = self._stage(data, tmp, mode, dest, syntax)
        rc, _, err = self.r.run(["mv", tmp, dest])
        if rc != 0:
            self.r.run(["rm", "-f", tmp])
            raise DeployError(f"{dest}: mv failed: {_dec(err)}")
        rc, out, _ = self.r.run(["md5sum", dest])
        if (parse_hash(out, "md5") if rc == 0 else None) != want:
            raise DeployError(f"{dest}: md5 MISMATCH after mv; check the device")
        self.out(f"  ok  {dest}  {len(data)} B  md5 {want}")

    def _swap_rcs(self, data: bytes, hooked: bool) -> str:
        """Stage + vet + mv + re-vet one candidate rcS.local. Returns 'ok' or a failure reason
        AFTER the mv (caller restores); raises before the mv with the original untouched."""
        want = self._stage(data, RCS_TMP, "755", RCS_LOCAL, syntax=True)
        back = self.read(RCS_TMP)
        problem = "unreadable" if back is None else rcs_shape_problem(_dec(back), hooked)
        if back is None or _md5(back) != want or problem:
            self.r.run(["rm", "-f", RCS_TMP])
            raise DeployError(
                f"{RCS_LOCAL}: candidate failed read-back checks ({problem or 'md5'}); "
                "temp file removed, original untouched"
            )
        rc, _, err = self.r.run(["mv", RCS_TMP, RCS_LOCAL])
        if rc != 0:
            self.r.run(["rm", "-f", RCS_TMP])
            raise DeployError(f"{RCS_LOCAL}: mv failed: {_dec(err)}; original untouched")
        rc, out, _ = self.r.run(["md5sum", RCS_LOCAL])
        if (parse_hash(out, "md5") if rc == 0 else None) != want:
            return "md5 mismatch after mv"
        rc, _, err = self.r.run(["sh", "-n", RCS_LOCAL])
        if rc != 0:
            return f"`sh -n` fails after mv: {_dec(err)[-200:]}"
        return "ok"

    def _write_rcs(self, data: bytes, hooked: bool, previous: bytes, why: str) -> None:
        """The only way rcS.local is ever written. A missing or broken rcS.local means no
        dropbear, so on any post-mv failure the previous (working) content is put back through
        the same staged, vetted path."""
        self.out(
            f"WRITE {RCS_LOCAL} ({why}): it lives on a unionfs over ubifs; rename atomicity there "
            "is UNKNOWN (never verified); the candidate is vetted on the device first and the "
            "previous content is restored on any failure"
        )
        res = self._swap_rcs(data, hooked)
        if res == "ok":
            self.out(f"  ok  {RCS_LOCAL}  {len(data)} B  md5 {_md5(data)}  (sh -n ok on device)")
            return
        self.out(f"POST-WRITE CHECK FAILED ({res}); restoring the previous {RCS_LOCAL}")
        try:
            again = self._swap_rcs(previous, not hooked)
        except DeployError as e:
            again = str(e)
        if again != "ok":
            raise DeployError(
                f"{RCS_LOCAL} write failed ({res}) AND the restore failed ({again}). The device "
                "may be locked out of SSH; do NOT reboot; fix over any open session, else "
                "Menu+Off factory reset"
            )
        raise DeployError(
            f"{RCS_LOCAL} write failed ({res}); previous content restored and verified"
        )

    def _mkdir_app(self) -> None:
        rc, _, err = self.r.run(["mkdir", "-p", APP_DIR])
        if rc != 0:
            raise DeployError(f"mkdir {APP_DIR} failed: {_dec(err)}")

    # -- status [read-only] -------------------------------------------------------------
    def status(self) -> int:
        p = self.out
        p(f"uname: {self.connect()}")
        rc, out, _ = self.r.run(["ps"])
        ours = [x for x in parse_ps(_dec(out)) if APP_DIR in x.cmd] if rc == 0 else []
        p("our processes: " + ("" if ours else "none"))
        for x in ours:
            p(f"  pid {x.pid}: {x.cmd}")
        rc, out, _ = self.r.run(["ls", "-l", APP_DIR])
        p(f"{APP_DIR}: " + ("" if rc == 0 else "absent"))
        if rc == 0:
            for ln in _dec(out).splitlines():
                if ln.strip():
                    p(f"  {ln}")
        rcs = self.read(RCS_LOCAL)
        if rcs is None:
            hook = "unknown (rcS.local unreadable)"
        else:
            hook = "installed" if HOOK_MARKER in _dec(rcs) else "not installed"
        p(f"boot hook: {hook}")
        sh = self.read(START_SH)
        m = re.search(r"--slot [0-9]+ --powermode 0x[0-9a-f]{2}", _dec(sh)) if sh else None
        p(f"start.sh app argv: {m[0] if m else 'unknown (start.sh absent or unrecognised)'}")
        p(f"DISABLE: {'PRESENT (hook will not launch)' if self.exists(DISABLE) else 'absent'}")
        count = self.read(BOOTCOUNT)
        p(f"boot counter: {_dec(count).strip() if count is not None else 'absent'}")
        for label, path in (("powersource", POWERSOURCE), ("battery soc", SOC)):
            v = self.read(path)
            p(f"{label}: {_dec(v).strip() if v is not None else 'unreadable'}")
        return 0

    # -- push [WRITE] -------------------------------------------------------------------
    def push(self, files: list[Path]) -> int:
        for f in files:
            if not f.is_file():
                raise DeployError(f"local file not found: {f}")
        names = [f.name for f in files]
        if len(set(names)) != len(names):
            raise DeployError(f"duplicate file names: {names}")
        self.connect()
        self._mkdir_app()
        for f in files:
            self._put(f.read_bytes(), f"{APP_DIR}/{f.name}", "755")
        self.out(f"push complete: {len(files)} file(s) verified by md5 on both ends")
        return 0

    # -- run [WRITE] --------------------------------------------------------------------
    def run_app(self, app: str, args: list[str]) -> int:
        self.connect()
        path = _need_write(f"{APP_DIR}/{app}")
        if self.r.run(["test", "-x", path])[0] != 0:
            raise DeployError(f"{path} missing or not executable: run push first")
        self.out(f"running {path} {shlex.join(args)} (foreground; Ctrl-C stops it)")
        return self.r.run_foreground([path, *args])

    # -- install-hook [WRITE] -----------------------------------------------------------
    def install_hook(
        self,
        app: str = DEFAULT_APP,
        slot: int = DEFAULT_SLOT,
        powermode: str = DEFAULT_POWERMODE,
        refresh_backup: bool = False,
    ) -> int:
        script = start_script(app, slot=slot, powermode=powermode)  # validates slot/powermode
        self.connect()
        raw = self.read(RCS_LOCAL)
        if raw is None:
            raise DeployError(f"cannot read {RCS_LOCAL}")
        text = _dec(raw)
        installed = text.count(HOOK_MARKER)
        if installed > 1:
            raise DeployError(
                f"{RCS_LOCAL} has {installed} hook lines; NOT editing. Found:\n{text}"
            )
        new = insert_hook(text) if installed == 0 else None  # refuses an unknown shape up front
        if installed == 0 and (problem := rcs_shape_problem(text, False)):
            raise DeployError(f"{RCS_LOCAL} {problem}; NOT editing")
        self._mkdir_app()
        have_backup = self.exists(RCS_BACKUP)
        if installed == 0:
            if not have_backup:  # back up the pristine file once
                self._put(raw, RCS_BACKUP, None)
            else:
                old = self.read(RCS_BACKUP)
                if old is not None and _md5(old) == _md5(raw):
                    self.out(f"  backup {RCS_BACKUP} already matches rcS.local; kept")
                elif refresh_backup:
                    self.out(
                        f"  --refresh-backup: replacing {RCS_BACKUP} with the current rcS.local"
                    )
                    self._put(raw, RCS_BACKUP, None)
                else:
                    raise DeployError(
                        f"{RCS_BACKUP} exists but differs from the current {RCS_LOCAL} (hook "
                        "absent): it is stale or from another state. NOT proceeding; inspect it, "
                        "or pass --refresh-backup to replace it with the current rcS.local"
                    )
        elif not have_backup:
            raise DeployError(f"hook is installed but {RCS_BACKUP} is missing; NOT proceeding")
        self._put(script.encode(), START_SH, "755", syntax=True)
        if new is None:
            self.out("hook already installed; rcS.local unchanged")
        else:
            self._write_rcs(new.encode(), True, raw, "install the boot hook")
            self.out(f"hook installed in {RCS_LOCAL}; app argv: {start_argv(slot, powermode)}")
        return 0

    # -- selftest [WRITE /var/volatile only] --------------------------------------------
    def selftest(self, slot: int = DEFAULT_SLOT, powermode: str = DEFAULT_POWERMODE) -> int:
        """Run start.sh + the hook line against a stub app under the device's own sh. Writes only
        under /var/volatile/hah-selftest, which is always removed afterwards."""
        script = start_script(slot=slot, powermode=powermode)
        self.connect()
        raw = self.read(RCS_LOCAL)
        if raw is None:
            raise DeployError(f"cannot read {RCS_LOCAL}")
        text = _dec(raw)
        hooked = text if HOOK_MARKER in text else insert_hook(text)  # a copy; never written back
        t = SELFTEST_DIR
        rc = 1
        try:
            rc0, _, err = self.r.run(["mkdir", "-p", t])
            if rc0 != 0:
                raise DeployError(f"mkdir {t} failed: {_dec(err)}")
            for name, data, mode in (
                ("start.sh", script.encode(), "755"),
                ("remote_selftest.sh", SELFTEST_SRC.read_bytes(), "755"),
                ("rcS.local.hooked", hooked.encode(), None),
                ("hookline.sh", (hook_line(t + "/app") + "\n").encode(), None),
            ):
                self._put(data, f"{t}/{name}", mode)
            rc, out, err = self.r.run(
                ["sh", f"{t}/remote_selftest.sh", t, start_argv(slot, powermode)]
            )
            for ln in (_dec(out) + _dec(err)).splitlines():
                self.out(f"  {ln}")
        finally:
            rm_rc, _, _ = self.r.run(["rm", "-rf", t])
            self.out(f"selftest dir {t} " + ("removed" if rm_rc == 0 else "NOT removed"))
        return 0 if rc == 0 else 1

    # -- mark-good [WRITE] --------------------------------------------------------------
    def mark_good(self) -> int:
        self.connect()
        self._mkdir_app()
        self._put(b"0\n", BOOTCOUNT, None)
        return 0

    # -- uninstall [WRITE] --------------------------------------------------------------
    def uninstall(self, purge: bool = False) -> int:
        self.connect()
        orig = self.read(RCS_BACKUP)
        if orig is None:
            raise DeployError(f"{RCS_BACKUP} missing: cannot restore rcS.local; NOT editing")
        if problem := rcs_shape_problem(_dec(orig), False):
            raise DeployError(f"{RCS_BACKUP} {problem}; refusing to restore it. NOT editing")
        cur = self.read(RCS_LOCAL)
        if cur is None:
            raise DeployError(f"cannot read {RCS_LOCAL}")
        self._write_rcs(orig, False, cur, "restore the backup")
        self.out(f"restored {RCS_LOCAL} from {RCS_BACKUP}; hook removed (md5 + sh -n verified)")
        if purge:
            rc, _, err = self.r.run(["rm", "-rf", APP_DIR])
            if rc != 0:
                raise DeployError(f"rm {APP_DIR} failed: {_dec(err)}")
            self.out(f"purged {APP_DIR}")
        else:
            self.out(f"left {APP_DIR} in place (use --purge to remove it)")
        return 0

    # -- reboot [WRITE] -----------------------------------------------------------------
    def reboot(
        self, down_timeout: float = 60.0, up_timeout: float = 300.0, interval: float = 3.0
    ) -> int:
        self.connect()
        self.out("rebooting the remote")
        rc, _, err = self.r.run(["reboot"])
        if rc not in (0, 255):
            raise DeployError(f"reboot failed (rc={rc}): {_dec(err)[-200:]}")
        if not self.wait(lambda: self.r.run(["uname", "-a"])[0] != 0, down_timeout, interval):
            raise DeployError("the remote stayed reachable; cannot confirm the reboot")
        if not self.wait(lambda: self.r.run(["uname", "-a"])[0] == 0, up_timeout, interval):
            raise DeployError(
                f"ssh did not return within {up_timeout:g}s. Check the USB cable and host "
                "address; if it never returns, Menu+Off factory-resets it."
            )
        self.out("ssh is back after reboot")
        return self.status()


def build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--host", default="192.168.2.1", help="default %(default)s")
    ap.add_argument("--port", type=int, default=None)
    ap.add_argument("--user", default="root")
    ap.add_argument("--key", default="~/.ssh/harmony_owner_ed25519")
    ap.add_argument("--ssh-timeout", type=int, default=DEFAULT_SSH_TIMEOUT, metavar="SEC")
    ap.add_argument("--app", default=DEFAULT_APP, help="app under /data/app (default %(default)s)")
    sub = ap.add_subparsers(dest="cmd", required=True)

    def add(name: str, help_: str, write: bool = True) -> argparse.ArgumentParser:
        p = sub.add_parser(name, help=help_, description=help_)
        if write:
            p.add_argument("--yes", action="store_true", help="confirm this WRITE step")
        return p

    add("status", "[read-only] kernel, our processes, /data/app, hook, boot count, battery", False)
    p = add("push", "[WRITE] copy static binaries into /data/app, md5-verified, chmod 755")
    p.add_argument("files", type=Path, nargs="+", help="app, rf_probe, remote_probe, ...")
    p = add("run", "[WRITE] run /data/app/<app> in the foreground over ssh (args after --)")
    p.add_argument("app_args", nargs=argparse.REMAINDER)
    p = add("install-hook", "[WRITE] back up rcS.local, add the guarded boot line, write start.sh")
    p.add_argument(
        "--slot", type=parse_slot, default=DEFAULT_SLOT, help="RF slot 1..15 (default %(default)s)"
    )
    p.add_argument("--powermode", type=parse_powermode, default=DEFAULT_POWERMODE,
                   help="RF powermode 0xNN (default %(default)s)")  # fmt: skip
    p.add_argument("--refresh-backup", action="store_true",
                   help="replace a stale rcS.local.orig with the current rcS.local")  # fmt: skip
    p = add("selftest", "[WRITE /var/volatile only] run start.sh + hook line against a stub app")
    p.add_argument("--slot", type=parse_slot, default=DEFAULT_SLOT)
    p.add_argument("--powermode", type=parse_powermode, default=DEFAULT_POWERMODE)
    add("mark-good", "[WRITE] reset the boot counter to 0")
    p = add("uninstall", "[WRITE] restore rcS.local from the backup (md5-verified)")
    p.add_argument("--purge", action="store_true", help="also remove /data/app")
    add("reboot", "[WRITE] reboot the remote, wait for ssh, report status")
    return ap


def main(
    argv: list[str] | None = None,
    runner: Runner | None = None,
    deployer: RemoteDeployer | None = None,
) -> int:
    a = build_parser().parse_args(argv)
    if a.cmd != "status" and not a.yes:
        print(f"{a.cmd} is a WRITE step on the real remote; re-run with --yes to confirm",
              file=sys.stderr)  # fmt: skip
        return 2
    d = deployer or RemoteDeployer(
        runner
        or HubSsh(
            a.host,
            a.user,
            a.key,
            timeout=a.ssh_timeout,
            run_timeout=DEFAULT_RUN_TIMEOUT,
            port=a.port,
        )
    )
    try:
        match a.cmd:
            case "status":
                return d.status()
            case "push":
                return d.push(a.files)
            case "run":
                args = a.app_args[1:] if a.app_args[:1] == ["--"] else a.app_args
                return d.run_app(a.app, args)
            case "install-hook":
                return d.install_hook(a.app, a.slot, a.powermode, a.refresh_backup)
            case "selftest":
                return d.selftest(a.slot, a.powermode)
            case "mark-good":
                return d.mark_good()
            case "uninstall":
                return d.uninstall(a.purge)
            case "reboot":
                return d.reboot()
    except DeployError as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        print("interrupted", file=sys.stderr)
        return 130
    return 1


if __name__ == "__main__":
    sys.exit(main())
