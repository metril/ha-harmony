#!/usr/bin/env python3
"""Deploy and run our cross-built app on the rooted Harmony Elite remote, over USB Ethernet SSH.

Files go only under /data/app (persistent), /etc/init.d/rcS.local (the boot hook, written
atomically via a temp file + mv) and /var/volatile (tmpfs). Never touches any mtd/ubi node, rffw,
mspfw, the watchdog, the charger or power-state sysfs files, and never uses dd.

The boot hook is one guarded line in rcS.local that backgrounds /data/app/start.sh after dropbear
(so it can never block SSH). start.sh counts boots; after 3 boots that were never marked good it
writes /data/app/DISABLE and stops launching the app. Touch /data/app/DISABLE to kill it by hand.
Recovery of last resort is Menu+Off (factory reset).

Subcommands are marked [read-only] or [WRITE]; every WRITE one needs --yes.
"""

import argparse
import hashlib
import posixpath
import shlex
import sys
import time
from collections.abc import Callable
from pathlib import Path

from deploy_hub import DeployError, HubSsh, Runner, parse_ps
from device_backup import DEFAULT_RUN_TIMEOUT, DEFAULT_SSH_TIMEOUT, parse_hash

APP_DIR = "/data/app"
RCS_LOCAL = "/etc/init.d/rcS.local"
RCS_TMP = RCS_LOCAL + ".new"
RCS_BACKUP = f"{APP_DIR}/rcS.local.orig"
START_SH = f"{APP_DIR}/start.sh"
BOOTCOUNT = f"{APP_DIR}/bootcount"
DISABLE = f"{APP_DIR}/DISABLE"
DEFAULT_APP = "harmony_remote"
MAX_BOOTS = 3
HOOK_MARKER = "# ha-harmony-hook"
# The PMIC exposes its nodes on a sub-device, not the i2c client itself (verified on the
# Elite 2026-11-17; the bare 1-0048/powersource does not exist).
POWERSOURCE = "/sys/bus/i2c/devices/1-0048/tps6507x-juniper/powersource"
SOC = "/sys/bus/i2c/devices/1-0070/soc"
VOLATILE = "/var/volatile"


def under_write_root(path: str) -> bool:
    """True only for /data/app/*, the rcS.local pair, and /var/volatile/*."""
    if ".." in path.split("/"):
        return False
    n = posixpath.normpath(path)
    return n in (RCS_LOCAL, RCS_TMP) or any(n.startswith(r + "/") for r in (APP_DIR, VOLATILE))


def _need_write(path: str) -> str:
    if not under_write_root(path):
        raise DeployError(f"internal error: refusing to write outside the allowed paths: {path}")
    return path


def hook_line(app_dir: str = APP_DIR) -> str:
    q = shlex.quote
    return (
        f"[ -x {q(app_dir + '/start.sh')} ] && [ ! -e {q(app_dir + '/DISABLE')} ] && "
        f"{q(app_dir + '/start.sh')} &  {HOOK_MARKER}"
    )


def start_script(app: str = DEFAULT_APP, max_boots: int = MAX_BOOTS) -> str:
    """start.sh: boot counter + crash-loop breaker. Paths are overridable for tests."""
    return f"""#!/bin/sh
# Generated by deploy_remote.py. Counts boots; disables itself after {max_boots} unhealthy ones.
APP_DIR="${{APP_DIR:-{APP_DIR}}}"
APP_BIN="${{APP_BIN:-$APP_DIR/{app}}}"
APP_LOG="${{APP_LOG:-{VOLATILE}/ha-harmony-app.log}}"
COUNT_FILE="$APP_DIR/bootcount"
[ -e "$APP_DIR/DISABLE" ] && exit 0
n=0
[ -f "$COUNT_FILE" ] && read n < "$COUNT_FILE"
case "$n" in ''|*[!0-9]*) n=0 ;; esac
n=$((n + 1))
echo "$n" > "$COUNT_FILE"
if [ "$n" -gt {max_boots} ]; then
    : > "$APP_DIR/DISABLE"
    exit 0
fi
[ -x "$APP_BIN" ] || exit 0
# The app (or `deploy_remote.py mark-good`) writes 0 here once it is healthy.
export HARMONY_BOOTCOUNT_FILE="$COUNT_FILE"
exec "$APP_BIN" >> "$APP_LOG" 2>&1
"""


def insert_hook(text: str) -> str:
    """Add the hook before the final `exit 0`; refuse any rcS.local of an unknown shape."""
    lines = text.split("\n")
    body = [i for i, ln in enumerate(lines) if ln.strip()]
    exit_i = body[-1] if body else -1
    has_exit = exit_i >= 0 and lines[exit_i].strip() == "exit 0"
    dropbear_i = [
        i for i, ln in enumerate(lines) if "dropbear" in ln and not ln.lstrip().startswith("#")
    ]
    if not has_exit or not dropbear_i or dropbear_i[0] > exit_i:
        raise DeployError(
            f"{RCS_LOCAL} has an unknown shape (need a dropbear line and a trailing `exit 0`); "
            f"NOT editing. Found:\n{text}"
        )
    lines.insert(exit_i, hook_line())
    return "\n".join(lines)


def _md5(data: bytes) -> str:
    return hashlib.md5(data, usedforsecurity=False).hexdigest()


def _dec(b: bytes) -> str:
    return b.decode("utf-8", "replace")


class RemoteDeployer:
    def __init__(
        self,
        runner: Runner,
        out: Callable[[str], None] = print,
        sleep: Callable[[float], None] = time.sleep,
        clock: Callable[[], float] = time.monotonic,
    ) -> None:
        self.r, self.out, self.sleep, self.clock = runner, out, sleep, clock

    # -- helpers ------------------------------------------------------------------------
    def connect(self) -> str:
        rc, out, err = self.r.run(["uname", "-a"])
        if rc != 0:
            raise DeployError(f"ssh/uname failed (rc={rc}): {_dec(err)[-200:]}")
        return _dec(out).strip()

    def read(self, path: str) -> bytes | None:
        rc, out, _ = self.r.run(["cat", path])
        return out if rc == 0 else None

    def exists(self, path: str) -> bool:
        return self.r.run(["test", "-e", path])[0] == 0

    def wait(self, pred: Callable[[], bool], timeout: float, interval: float = 2.0) -> bool:
        deadline = self.clock() + timeout
        while True:
            if pred():
                return True
            if self.clock() >= deadline:
                return False
            self.sleep(interval)

    def _put(self, data: bytes, dest: str, mode: str | None, tmp: str | None = None) -> None:
        """Atomic, md5-verified write: temp in the same directory, verify, chmod, mv."""
        tmp = tmp or dest + ".new"
        _need_write(dest)
        _need_write(tmp)
        want = _md5(data)
        rc, _, err = self.r.run_input(["sh", "-c", f"cat > {shlex.quote(tmp)}"], data)
        if rc != 0:
            self.r.run(["rm", "-f", tmp])
            raise DeployError(f"{dest}: upload failed (rc={rc}): {_dec(err)}")
        rc, out, _ = self.r.run(["md5sum", tmp])
        got = parse_hash(out, "md5") if rc == 0 else None
        if got != want:
            self.r.run(["rm", "-f", tmp])  # never leave an unverified file behind
            raise DeployError(
                f"{dest}: md5 MISMATCH (local {want}, device {got or 'unreadable'}); "
                "temp file removed, destination untouched"
            )
        if mode:
            rc, _, err = self.r.run(["chmod", mode, tmp])
            if rc != 0:
                self.r.run(["rm", "-f", tmp])
                raise DeployError(f"{dest}: chmod failed: {_dec(err)}")
        rc, _, err = self.r.run(["mv", tmp, dest])
        if rc != 0:
            self.r.run(["rm", "-f", tmp])
            raise DeployError(f"{dest}: mv failed: {_dec(err)}")
        rc, out, _ = self.r.run(["md5sum", dest])
        if (parse_hash(out, "md5") if rc == 0 else None) != want:
            raise DeployError(f"{dest}: md5 MISMATCH after mv; check the device")
        self.out(f"  ok  {dest}  {len(data)} B  md5 {want}")

    def _mkdir_app(self) -> None:
        rc, _, err = self.r.run(["mkdir", "-p", APP_DIR])
        if rc != 0:
            raise DeployError(f"mkdir {APP_DIR} failed: {_dec(err)}")

    # -- status [read-only] -------------------------------------------------------------
    def status(self) -> int:
        p = self.out
        p(f"uname: {self.connect()}")
        rc, out, _ = self.r.run(["ps"])
        ours = [x for x in parse_ps(_dec(out)) if APP_DIR in x.cmd] if rc == 0 else []
        p("our processes: " + ("" if ours else "none"))
        for x in ours:
            p(f"  pid {x.pid}: {x.cmd}")
        rc, out, _ = self.r.run(["ls", "-l", APP_DIR])
        p(f"{APP_DIR}: " + ("" if rc == 0 else "absent"))
        if rc == 0:
            for ln in _dec(out).splitlines():
                if ln.strip():
                    p(f"  {ln}")
        rcs = self.read(RCS_LOCAL)
        if rcs is None:
            hook = "unknown (rcS.local unreadable)"
        else:
            hook = "installed" if HOOK_MARKER in _dec(rcs) else "not installed"
        p(f"boot hook: {hook}")
        p(f"DISABLE: {'PRESENT (hook will not launch)' if self.exists(DISABLE) else 'absent'}")
        count = self.read(BOOTCOUNT)
        p(f"boot counter: {_dec(count).strip() if count is not None else 'absent'}")
        for label, path in (("powersource", POWERSOURCE), ("battery soc", SOC)):
            v = self.read(path)
            p(f"{label}: {_dec(v).strip() if v is not None else 'unreadable'}")
        return 0

    # -- push [WRITE] -------------------------------------------------------------------
    def push(self, files: list[Path]) -> int:
        for f in files:
            if not f.is_file():
                raise DeployError(f"local file not found: {f}")
        names = [f.name for f in files]
        if len(set(names)) != len(names):
            raise DeployError(f"duplicate file names: {names}")
        self.connect()
        self._mkdir_app()
        for f in files:
            self._put(f.read_bytes(), f"{APP_DIR}/{f.name}", "755")
        self.out(f"push complete: {len(files)} file(s) verified by md5 on both ends")
        return 0

    # -- run [WRITE] --------------------------------------------------------------------
    def run_app(self, app: str, args: list[str]) -> int:
        self.connect()
        path = _need_write(f"{APP_DIR}/{app}")
        if self.r.run(["test", "-x", path])[0] != 0:
            raise DeployError(f"{path} missing or not executable: run push first")
        self.out(f"running {path} {shlex.join(args)} (foreground; Ctrl-C stops it)")
        return self.r.run_foreground([path, *args])

    # -- install-hook [WRITE] -----------------------------------------------------------
    def install_hook(self, app: str = DEFAULT_APP) -> int:
        self.connect()
        raw = self.read(RCS_LOCAL)
        if raw is None:
            raise DeployError(f"cannot read {RCS_LOCAL}")
        text = _dec(raw)
        installed = text.count(HOOK_MARKER)
        if installed > 1:
            raise DeployError(
                f"{RCS_LOCAL} has {installed} hook lines; NOT editing. Found:\n{text}"
            )
        new = insert_hook(text) if installed == 0 else None  # refuses an unknown shape up front
        self._mkdir_app()
        if installed == 0:  # back up the pristine file once; never overwrite a backup
            if self.exists(RCS_BACKUP):
                self.out(f"  backup {RCS_BACKUP} already exists; kept")
            else:
                self._put(raw, RCS_BACKUP, None)
        elif not self.exists(RCS_BACKUP):
            raise DeployError(f"hook is installed but {RCS_BACKUP} is missing; NOT proceeding")
        self._put(start_script(app).encode(), START_SH, "755")
        if new is None:
            self.out("hook already installed; rcS.local unchanged")
        else:
            self._put(new.encode(), RCS_LOCAL, "755", tmp=RCS_TMP)
            self.out(f"hook installed in {RCS_LOCAL}")
        return 0

    # -- mark-good [WRITE] --------------------------------------------------------------
    def mark_good(self) -> int:
        self.connect()
        self._mkdir_app()
        self._put(b"0\n", BOOTCOUNT, None)
        return 0

    # -- uninstall [WRITE] --------------------------------------------------------------
    def uninstall(self, purge: bool = False) -> int:
        self.connect()
        orig = self.read(RCS_BACKUP)
        if orig is None:
            raise DeployError(f"{RCS_BACKUP} missing: cannot restore rcS.local; NOT editing")
        self._put(orig, RCS_LOCAL, "755", tmp=RCS_TMP)
        self.out(f"restored {RCS_LOCAL} from {RCS_BACKUP}; hook removed")
        if purge:
            rc, _, err = self.r.run(["rm", "-rf", APP_DIR])
            if rc != 0:
                raise DeployError(f"rm {APP_DIR} failed: {_dec(err)}")
            self.out(f"purged {APP_DIR}")
        else:
            self.out(f"left {APP_DIR} in place (use --purge to remove it)")
        return 0

    # -- reboot [WRITE] -----------------------------------------------------------------
    def reboot(
        self, down_timeout: float = 60.0, up_timeout: float = 300.0, interval: float = 3.0
    ) -> int:
        self.connect()
        self.out("rebooting the remote")
        rc, _, err = self.r.run(["reboot"])
        if rc not in (0, 255):
            raise DeployError(f"reboot failed (rc={rc}): {_dec(err)[-200:]}")
        if not self.wait(lambda: self.r.run(["uname", "-a"])[0] != 0, down_timeout, interval):
            raise DeployError("the remote stayed reachable; cannot confirm the reboot")
        if not self.wait(lambda: self.r.run(["uname", "-a"])[0] == 0, up_timeout, interval):
            raise DeployError(
                f"ssh did not return within {up_timeout:g}s. Check the USB cable and host "
                "address; if it never returns, Menu+Off factory-resets it."
            )
        self.out("ssh is back after reboot")
        return self.status()


def build_parser() -> argparse.ArgumentParser:
    ap = argparse.ArgumentParser(description=__doc__, formatter_class=argparse.RawTextHelpFormatter)
    ap.add_argument("--host", default="192.168.2.1", help="default %(default)s")
    ap.add_argument("--port", type=int, default=None)
    ap.add_argument("--user", default="root")
    ap.add_argument("--key", default="~/.ssh/harmony_owner_ed25519")
    ap.add_argument("--ssh-timeout", type=int, default=DEFAULT_SSH_TIMEOUT, metavar="SEC")
    ap.add_argument("--app", default=DEFAULT_APP, help="app under /data/app (default %(default)s)")
    sub = ap.add_subparsers(dest="cmd", required=True)

    def add(name: str, help_: str, write: bool = True) -> argparse.ArgumentParser:
        p = sub.add_parser(name, help=help_, description=help_)
        if write:
            p.add_argument("--yes", action="store_true", help="confirm this WRITE step")
        return p

    add("status", "[read-only] kernel, our processes, /data/app, hook, boot count, battery", False)
    p = add("push", "[WRITE] copy static binaries into /data/app, md5-verified, chmod 755")
    p.add_argument("files", type=Path, nargs="+", help="app, rf_probe, remote_probe, ...")
    p = add("run", "[WRITE] run /data/app/<app> in the foreground over ssh (args after --)")
    p.add_argument("app_args", nargs=argparse.REMAINDER)
    add("install-hook", "[WRITE] back up rcS.local, add the guarded boot line, write start.sh")
    add("mark-good", "[WRITE] reset the boot counter to 0")
    p = add("uninstall", "[WRITE] restore rcS.local from the backup (md5-verified)")
    p.add_argument("--purge", action="store_true", help="also remove /data/app")
    add("reboot", "[WRITE] reboot the remote, wait for ssh, report status")
    return ap


def main(
    argv: list[str] | None = None,
    runner: Runner | None = None,
    deployer: RemoteDeployer | None = None,
) -> int:
    a = build_parser().parse_args(argv)
    if a.cmd != "status" and not a.yes:
        print(f"{a.cmd} is a WRITE step on the real remote; re-run with --yes to confirm",
              file=sys.stderr)  # fmt: skip
        return 2
    d = deployer or RemoteDeployer(
        runner
        or HubSsh(
            a.host,
            a.user,
            a.key,
            timeout=a.ssh_timeout,
            run_timeout=DEFAULT_RUN_TIMEOUT,
            port=a.port,
        )
    )
    try:
        match a.cmd:
            case "status":
                return d.status()
            case "push":
                return d.push(a.files)
            case "run":
                args = a.app_args[1:] if a.app_args[:1] == ["--"] else a.app_args
                return d.run_app(a.app, args)
            case "install-hook":
                return d.install_hook(a.app)
            case "mark-good":
                return d.mark_good()
            case "uninstall":
                return d.uninstall(a.purge)
            case "reboot":
                return d.reboot()
    except DeployError as e:
        print(f"ERROR: {e}", file=sys.stderr)
        return 1
    except KeyboardInterrupt:
        print("interrupted", file=sys.stderr)
        return 130
    return 1


if __name__ == "__main__":
    sys.exit(main())
