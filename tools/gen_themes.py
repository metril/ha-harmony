"""Generate theme tables + shared test vectors from proto/themes.yaml (a test fails when stale).

Computes each palette entry's INK (TX or BG, whichever contrasts more) and PRESSED colour with the
integer reference in harmony_core/theme_math.py, validates every preset (text-on-surface pairs,
ink >= 4.5:1, RGB565 exactness, ids) and writes harmony_core/themes.py, remote/app/theme_presets.[ch],
addon/frontend/src/lib/themes.ts and tests/vectors/themes.json.
Usage: uv run python tools/gen_themes.py
"""

from __future__ import annotations

import json
import random
import sys
from pathlib import Path

import yaml

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))
from harmony_core import theme_math as tm

SRC = ROOT / "proto" / "themes.yaml"
OUT_PY = ROOT / "harmony_core" / "themes.py"
OUT_C = ROOT / "remote" / "app" / "theme_presets.c"
OUT_H = ROOT / "remote" / "app" / "theme_presets.h"
OUT_TS = ROOT / "addon" / "frontend" / "src" / "lib" / "themes.ts"
OUT_VEC = ROOT / "tests" / "vectors" / "themes.json"
CUSTOM_ID = 7
MIN_PRESSED = (3, 1)  # pressed fill vs its ink, presets only


def _hex(s: str) -> int:
    assert s.startswith("#") and len(s) == 7, s
    return int(s[1:], 16)


def load() -> tuple[list[str], list[dict]]:
    doc = yaml.safe_load(SRC.read_text())
    names = doc["palette"]
    errs: list[str] = []
    if tuple(names) != tm.PALETTE_NAMES:
        errs.append("palette order differs from theme_math.PALETTE_NAMES")
    themes, ids, keys = [], set(), set()
    for t in doc["themes"]:
        k = t["key"]
        if t["id"] in ids or k in keys or not 0 <= t["id"] < CUSTOM_ID:
            errs.append(f"{k}: id {t['id']} duplicate or not in 0..{CUSTOM_ID - 1}")
        ids.add(t["id"])
        keys.add(k)
        if set(t["tokens"]) != set(tm.TOKEN_NAMES) or set(t["palette"]) != set(names):
            errs.append(f"{k}: token or palette names do not match the schema")
            continue
        tk = {n: _hex(t["tokens"][n]) for n in tm.TOKEN_NAMES}
        for n, v in tk.items():
            if not tm.is565(v):
                errs.append(f"{k}: token {n} #{v:06x} is not RGB565-exact")
        pal = []
        for nm in names:
            fill = _hex(t["palette"][nm])
            if not tm.is565(fill):
                errs.append(f"{k}: palette {nm} #{fill:06x} is not RGB565-exact")
            i = tm.ink(fill, tk["tx"], tk["bg"])
            p = tm.pressed(fill, i)
            if not tm.meets(i, p, *MIN_PRESSED):
                errs.append(f"{k}: palette {nm} pressed contrast {tm.contrast_x100(i, p) / 100:.2f}:1 < 3")
            pal.append({"name": nm, "fill": fill, "ink": i, "pressed": p})
        for pr in tm.validate_theme(tk, [p["fill"] for p in pal]):
            errs.append(
                f"{k}: {pr['text']} on {pr['surface']} is {pr['ratio_x100'] / 100:.2f}:1, needs {pr['min_x100'] / 100}"
            )
        themes.append({"id": t["id"], "key": k, "name": t["name"], "tokens": tk, "palette": pal})
    if errs:
        raise SystemExit("themes.yaml:\n  " + "\n  ".join(errs))
    themes.sort(key=lambda t: t["id"])
    return names, themes


def emit_py(names: list[str], themes: list[dict]) -> str:
    head = (
        '"""Theme presets (GENERATED by tools/gen_themes.py from proto/themes.yaml; do not edit).\n\n'
        'Colours are 0xRRGGBB ints. Maths lives in harmony_core/theme_math.py."""\n\n'
        "from __future__ import annotations\n\n"
        "from typing import NamedTuple\n\n"
        "from .theme_math import PALETTE_NAMES, TOKEN_NAMES\n\n"
        f"CUSTOM_ID = {CUSTOM_ID}  # reserved for a custom theme; presets are 0..{CUSTOM_ID - 1}\n"
        "__all__ = [\"CUSTOM_ID\", \"PALETTE_NAMES\", \"TOKEN_NAMES\"]\n\n\n"
        "class Swatch(NamedTuple):\n    name: str\n    fill: int\n    ink: int\n    pressed: int\n\n\n"
        "class Theme(NamedTuple):\n    id: int\n    key: str\n    name: str\n    tokens: dict[str, int]\n    palette: tuple[Swatch, ...]\n\n\n"
        "THEMES: tuple[Theme, ...] = (\n"
    )
    out = [head]
    for t in themes:
        out.append(f"    Theme(\n        {t['id']},\n        {t['key']!r},\n        {t['name']!r},\n        {{\n")
        out += [f"            {k!r}: 0x{v:06X},\n" for k, v in t["tokens"].items()]
        out.append("        },\n        (\n")
        out += [
            f"            Swatch({p['name']!r}, 0x{p['fill']:06X}, 0x{p['ink']:06X}, 0x{p['pressed']:06X}),\n"
            for p in t["palette"]
        ]
        out.append("        ),\n    ),\n")
    out.append(
        ")\nTHEME_IDS: dict[str, int] = {t.key: t.id for t in THEMES}\n"
        "PRESETS: dict[str, Theme] = {t.key: t for t in THEMES}\n\n\n"
        "def theme_by_id(theme_id: int) -> Theme | None:\n"
        "    return next((t for t in THEMES if t.id == theme_id), None)\n\n\n"
        "def swatch(theme_id: int, index: int) -> Swatch | None:\n"
        '    """Palette entry for wire index 1..12 (0 or out of range: None = role default)."""\n'
        "    t = theme_by_id(theme_id)\n"
        "    if t is None or not 1 <= index <= len(t.palette):\n        return None\n"
        "    return t.palette[index - 1]\n"
    )
    return "".join(out)


def emit_h(names: list[str], themes: list[dict]) -> str:
    toks = "\n".join(f"    uint32_t {k};" for k in tm.TOKEN_NAMES)
    return (
        "/* GENERATED by tools/gen_themes.py from proto/themes.yaml; do not edit. */\n"
        "#ifndef RA_THEME_PRESETS_H\n#define RA_THEME_PRESETS_H\n\n#include <stdint.h>\n\n"
        f"#define RA_THEME_COUNT {len(themes)}\n"
        f"#define RA_THEME_CUSTOM_ID {CUSTOM_ID} /* reserved */\n"
        f"#define RA_PALETTE_N {len(names)} /* wire index 1..N; 0 = no colour */\n\n"
        + "".join(f"#define RA_THEME_{t['key'].upper()} {t['id']}\n" for t in themes)
        + "\ntypedef struct {\n    uint32_t fill, ink, pressed; /* 0xRRGGBB */\n} ra_swatch_t;\n\n"
        f"/* token fields are in wire order (theme_derive.h) */\n"
        f"typedef struct {{\n    uint8_t id;\n    const char *key, *name;\n{toks}\n    ra_swatch_t palette[RA_PALETTE_N];\n}} ra_theme_t;\n\n"
        "extern const ra_theme_t ra_themes[RA_THEME_COUNT];\n"
        "extern const uint16_t ra_lin[256]; /* 12-bit sRGB->linear, see theme_derive.c */\n"
        "const ra_theme_t *ra_theme_find(uint8_t id); /* NULL when unknown */\n\n#endif\n"
    )


def emit_c(names: list[str], themes: list[dict]) -> str:
    out = [
        '/* GENERATED by tools/gen_themes.py from proto/themes.yaml; do not edit. */\n#include "remote/app/theme_presets.h"\n\n',
        "const uint16_t ra_lin[256] = {",
    ]
    out.append(",".join(("\n    " if i % 16 == 0 else " ") + str(v) for i, v in enumerate(tm.LIN)) + "};\n\n")
    out.append("const ra_theme_t ra_themes[RA_THEME_COUNT] = {\n")
    for t in themes:
        tk = ", ".join(f"0x{t['tokens'][k]:06X}" for k in tm.TOKEN_NAMES)
        out.append(f'    {{{t["id"]}, "{t["key"]}", "{t["name"]}",\n     {tk},\n     {{\n')
        out += [
            f"         {{0x{p['fill']:06X}, 0x{p['ink']:06X}, 0x{p['pressed']:06X}}}, /* {p['name']} */\n"
            for p in t["palette"]
        ]
        out.append("     }},\n")
    out.append(
        "};\n\nconst ra_theme_t *ra_theme_find(uint8_t id)\n{\n"
        "    for (unsigned i = 0; i < RA_THEME_COUNT; i++)\n        if (ra_themes[i].id == id)\n            return &ra_themes[i];\n"
        "    return 0;\n}\n"
    )
    return "".join(out)


def emit_ts(names: list[str], themes: list[dict]) -> str:
    h = lambda v: f"0x{v:06x}"
    out = [
        "// GENERATED by tools/gen_themes.py from proto/themes.yaml; do not edit.\n// Colours are 0xRRGGBB numbers; maths lives in theme-math.ts.\n\n",
        f"export const CUSTOM_THEME_ID = {CUSTOM_ID}; // reserved; presets are 0..{CUSTOM_ID - 1}\n",
        f"export const TOKEN_NAMES = [{', '.join(repr(k) for k in tm.TOKEN_NAMES)}] as const;\n",
        f"export const PALETTE_NAMES = [{', '.join(repr(n) for n in names)}] as const; // wire index 1..{len(names)}\n",
        "export const LIN: readonly number[] = [" + ",".join(("\n  " if i % 16 == 0 else " ") + str(v) for i, v in enumerate(tm.LIN)) + "];\n\n",
        "export type TokenName = (typeof TOKEN_NAMES)[number];\nexport type PaletteName = (typeof PALETTE_NAMES)[number];\n",
        "export interface Swatch {\n  name: PaletteName;\n  fill: number;\n  ink: number;\n  pressed: number;\n}\n",
        "export interface Theme {\n  id: number;\n  key: string;\n  name: string;\n  tokens: Record<TokenName, number>;\n  palette: readonly Swatch[];\n}\n\n",
        "export const THEMES: readonly Theme[] = [\n",
    ]
    for t in themes:
        out.append(f"  {{\n    id: {t['id']},\n    key: '{t['key']}',\n    name: '{t['name']}',\n    tokens: {{\n")
        out += [f"      {k}: {h(v)},\n" for k, v in t["tokens"].items()]
        out.append("    },\n    palette: [\n")
        out += [
            f"      {{ name: '{p['name']}', fill: {h(p['fill'])}, ink: {h(p['ink'])}, pressed: {h(p['pressed'])} }},\n"
            for p in t["palette"]
        ]
        out.append("    ],\n  },\n")
    out.append(
        "];\n\nexport function themeById(id: number): Theme | undefined {\n  return THEMES.find((t) => t.id === id);\n}\n\n"
        "/** Palette entry for wire index 1..12 (0 or out of range: undefined = role default). */\n"
        "export function swatchOf(theme: Theme, index: number): Swatch | undefined {\n  return theme.palette[index - 1];\n}\n\n"
        "export function css(c: number): string {\n  return `#${c.toString(16).padStart(6, '0')}`;\n}\n"
    )
    return "".join(out)


def _tie_margin(f: int, tx: int, bg: int) -> int:
    nt, dt = tm._hilo(f, tx)
    nb, db = tm._hilo(f, bg)
    return abs(nt * db - nb * dt) * 10**6 // max(nt * db, 1)


def vectors(names: list[str], themes: list[dict]) -> dict:
    rnd = random.Random(565)
    rc = lambda: rnd.randrange(1 << 24)
    edge = [0, 0xFFFFFF, 0xF8FCF8, 0x101820, 0x808080, 0x7F7F7F, 0xFF0000, 0x00FF00, 0x0000FF, 0xFCFCFC, 0x040404, 0x010101, 0xFEFEFE]
    derive = [[f, t, b] for f in edge for t, b in ((0xF8FCF8, 0), (0, 0xF8FCF8), (0xF8FCF8, 0xF8FCF8), (0x101820, 0xE8ECF0))]
    near = sorted(((rc(), rc(), rc()) for _ in range(60000)), key=lambda x: _tie_margin(*x))[:120]
    derive += [list(x) for x in near]
    # tx and bg swapped on the same fill must agree except on exact ties (tx wins)
    derive += [[rc(), rc(), rc()] for _ in range(180)]
    derive = [[f, t, b, i, tm.pressed(f, i)] for f, t, b in derive for i in [tm.ink(f, t, b)]]
    snap = [[c, tm.snap565(c)] for c in [*edge, 0xFB, 0xFC, 0xFD, 0xFEFEFE, 0x040204, 0x030103, 0x020002, *[rc() for _ in range(80)]]]
    contrast = [[a, b, tm.contrast_x100(a, b)] for a, b in [(0, 0xFFFFFF), (0x101820, 0xF8FCF8), *[(rc(), rc()) for _ in range(60)]]]
    outline = [[f, b, tm.needs_outline(f, b)] for f, b in [(0x101820, 0x101820), (0x182430, 0x101820), (0x202C38, 0x101820), *[(rc(), rc()) for _ in range(40)]]]
    wires = []
    for t in themes:
        fills = [p["fill"] for p in t["palette"]]
        wires.append({"key": t["key"], "tokens": t["tokens"], "fills": fills, "hex": tm.serialise_theme(t["tokens"], fills).hex()})
    for _ in range(12):  # free colours
        tk = {k: rc() for k in tm.TOKEN_NAMES}
        fl = [rc() for _ in names]
        wires.append({"key": None, "tokens": {k: tm.snap565(v) for k, v in tk.items()}, "fills": [tm.snap565(f) for f in fl], "hex": tm.serialise_theme(tk, fl).hex()})
    good = bytes.fromhex(wires[0]["hex"])
    wire_bad = [good[:-1].hex(), (good + b"\0").hex(), b"".hex(), bytes([2]).hex() + good[1:].hex(), bytes([0]).hex() + good[1:].hex()]
    d = themes[0]["tokens"]
    bad_sets = [
        {**d, "tx": d["bg"]},
        {**d, "tx2": 0x303840, "tx3": 0x202830},
        {**d, "onacc": 0x20C8B0},
        {**d, "bg": 0xF8FCF8, "s1": 0xF0F4F0},
        {**d, "onbad": 0xF85848, "onwarm": 0xF8C040},
    ]
    pal0 = [p["fill"] for p in themes[0]["palette"]]
    validate = [{"tokens": tk, "fills": pal0, "problems": tm.validate_theme(tk, pal0)} for tk in bad_sets]
    validate.append({"tokens": d, "fills": [0x808080] * 12, "problems": tm.validate_theme(d, [0x808080] * 12)})
    validate.append({"tokens": d, "fills": None, "problems": tm.validate_theme(d)})
    pals = [p["fill"] for p in themes[0]["palette"]]
    nearest = [[c, tm.nearest_palette(c, pals)] for c in [*pals, 0xFF0000, 0x00FF00, 0x0000FF, 0x808080, 0xFFFFFF, 0, 0xFF8000, 0x8000FF]]
    return {
        "lin": list(tm.LIN),
        "snap": snap,
        "contrast": contrast,
        "derive": derive,  # [fill, tx, bg, ink, pressed]
        "outline": outline,  # [fill, bg, needs_outline]
        "wire": wires,
        "wire_bad": wire_bad,
        "validate": validate,
        "nearest_palette": {"fills_of": "default", "cases": nearest},
    }


def outputs() -> dict[Path, str]:
    names, themes = load()
    return {
        OUT_PY: emit_py(names, themes),
        OUT_H: emit_h(names, themes),
        OUT_C: emit_c(names, themes),
        OUT_TS: emit_ts(names, themes),
        OUT_VEC: json.dumps(vectors(names, themes), separators=(",", ":")) + "\n",
    }


if __name__ == "__main__":
    for path, text in outputs().items():
        path.write_text(text)
        print("wrote", path.relative_to(ROOT))
