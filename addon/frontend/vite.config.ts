import { fileURLToPath } from 'node:url';
import { defineConfig } from 'vitest/config';

// Lit `css` templates are shipped as text: drop their comments and indentation (the gzip budget counts every byte).
const minifyCss = {
  name: 'minify-lit-css',
  enforce: 'pre' as const,
  transform(code: string, id: string) {
    if (!id.includes('/src/') || !id.endsWith('.ts') || !code.includes('css`')) return null;
    return code.replace(/\bcss`([^`]*)`/g, (_m, body: string) => 'css`' + body.replace(/\/\*[\s\S]*?\*\//g, '').replace(/\s*\n\s*/g, ' ').replace(/ {2,}/g, ' ').trim() + '`');
  },
};

// One JS + one CSS (content-hashed), relative URLs so the page works under any ingress prefix.
export default defineConfig({
  plugins: [minifyCss],
  base: './',
  // Data shared with the Python side (generated by tools/gen_icons.py) lives outside this package.
  resolve: { alias: { '@shared': fileURLToPath(new URL('../../harmony_addon/frontend-shared', import.meta.url)) } },
  build: {
    target: 'es2022',
    cssCodeSplit: false,
    modulePreload: false,
    assetsInlineLimit: 0,

  },
  test: {
    environment: 'happy-dom',
    include: ['test/**/*.test.ts'],
  },
});
